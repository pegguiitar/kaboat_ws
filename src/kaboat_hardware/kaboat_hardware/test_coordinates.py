# ==============================================================================
# 보조 헬퍼 함수 (노드 및 런치 파일에서 사용)
# ==============================================================================
def get_bspline_control_points_xy() -> Tuple[List[float], List[float]]:
    """BSPLINE_TRACK의 control_points를 X좌표 리스트와 Y좌표 리스트로 분리 반환."""
    cps = BSPLINE_TRACK.get('control_points', [])
    xs = [float(p[0]) for p in cps]
    ys = [float(p[1]) for p in cps]
    return xs, ys

